-- Schema demo (terpisah dari schema service TokoKu). Seed: 30 order x 3 item.
CREATE SEQUENCE purchase_order_seq START WITH 1001 INCREMENT BY 50;
CREATE SEQUENCE order_line_seq START WITH 1001 INCREMENT BY 50;
CREATE SEQUENCE seq_item_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE purchase_order (
    id          bigint PRIMARY KEY,
    customer    varchar(40) NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE order_line (
    id        bigint PRIMARY KEY,
    order_id  bigint NOT NULL REFERENCES purchase_order (id),
    sku       varchar(40) NOT NULL,
    quantity  int NOT NULL
);

INSERT INTO purchase_order (id, customer) SELECT g, 'cust-' || (g % 5) FROM generate_series(1, 30) g;
INSERT INTO order_line (id, order_id, sku, quantity)
SELECT (o - 1) * 3 + i, o, 'SKU-' || i, i FROM generate_series(1, 30) o, generate_series(1, 3) i;

